/**
 * Gives every seeded seller a real devnet keypair and signs their listings for real.
 *
 * Two problems this fixes at once. The hand-written seller wallets in the catalogue were not
 * valid Solana addresses, so any purchase outside ds-001 died with "is not a Solana address"
 * rather than refusing gracefully. And every listing carried `signature: null`, so
 * verify_provenance could only ever say "pending" and the agent bought rows it had not
 * verified. Now a seller signs, and the buyer checks the signature.
 *
 * Secrets go to .sellers.json, which is gitignored. Only public keys and signatures are
 * committed, which is the whole point: a buyer verifies without holding a seller's key.
 *
 * One listing is signed over a deliberately different payload (TAMPERED_ID) so that a
 * listing edited after signing exists in the catalogue. The agent must refuse it. That is a
 * demo beat, not an accident — see the comment at the top of lib/data/catalog.ts.
 */
import { createPrivateKey, createPublicKey, generateKeyPairSync, sign as cryptoSign } from "node:crypto";
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { getBase58Decoder } from "@solana/kit";
import { CATALOG } from "../lib/data/catalog";
import { canonicalBytes } from "../lib/provenance/canonical";
import type { DatasetListing } from "../lib/data/types";

const SECRETS_PATH = ".sellers.json";
const OUT_PATH = "lib/data/provenance.generated.ts";

/** Listings that must stay unverifiable, and why. */
const UNSIGNED_IDS = new Set(["ds-007"]); // claims no seller identity at all
const TAMPERED_ID = process.env.TAMPERED_ID ?? "ds-008"; // signed, then the listing was edited

const PKCS8_ED25519_PREFIX = Buffer.from("302e020100300506032b657004220420", "hex");
const b58 = getBase58Decoder();

type Secrets = Record<string, string>; // seller name -> 32-byte seed, hex

function loadSecrets(): Secrets {
  return existsSync(SECRETS_PATH) ? JSON.parse(readFileSync(SECRETS_PATH, "utf8")) : {};
}

function seedFor(secrets: Secrets, sellerName: string): Buffer {
  if (!secrets[sellerName]) {
    const { privateKey } = generateKeyPairSync("ed25519");
    const der = privateKey.export({ format: "der", type: "pkcs8" }) as Buffer;
    secrets[sellerName] = der.subarray(der.length - 32).toString("hex");
  }
  return Buffer.from(secrets[sellerName], "hex");
}

function keysFromSeed(seed: Buffer) {
  const privateKey = createPrivateKey({
    key: Buffer.concat([PKCS8_ED25519_PREFIX, seed]),
    format: "der",
    type: "pkcs8",
  });
  const raw = (createPublicKey(privateKey).export({ format: "der", type: "spki" }) as Buffer).subarray(-32);
  return { privateKey, wallet: b58.decode(raw) };
}

const secrets = loadSecrets();
const wallets: Record<string, string> = {};
const signatures: Record<string, string> = {};

for (const dataset of CATALOG) {
  if (!dataset.provenance.signedBy) continue; // ds-007: no identity, nothing to sign with
  const { privateKey, wallet } = keysFromSeed(seedFor(secrets, dataset.seller.name));
  wallets[dataset.seller.name] = wallet;
}

for (const dataset of CATALOG) {
  if (UNSIGNED_IDS.has(dataset.id) || !dataset.provenance.signedBy) continue;

  const wallet = wallets[dataset.seller.name];
  const { privateKey } = keysFromSeed(seedFor(secrets, dataset.seller.name));

  // Sign the listing exactly as it will be served, with the real wallet substituted in.
  const asServed: DatasetListing = { ...dataset, seller: { ...dataset.seller, wallet } };

  // The tampered one is signed over a smaller row count than it advertises: the seller
  // attested to one thing and the listing now says another.
  const signedOver: DatasetListing =
    dataset.id === TAMPERED_ID ? { ...asServed, rows: Math.floor(asServed.rows / 2) } : asServed;

  signatures[dataset.id] = b58.decode(cryptoSign(null, canonicalBytes(signedOver), privateKey));
}

writeFileSync(SECRETS_PATH, `${JSON.stringify(secrets, null, 2)}\n`);
writeFileSync(
  OUT_PATH,
  `// Generated by \`npm run sign:catalog\`. Do not edit by hand.
// Seller wallets are real devnet ed25519 public keys; signatures are real ed25519 signatures
// by those keys over the listing's canonical payload (lib/provenance/canonical.ts).
export const SELLER_WALLETS: Record<string, string> = ${JSON.stringify(wallets, null, 2)};

export const LISTING_SIGNATURES: Record<string, string> = ${JSON.stringify(signatures, null, 2)};
`,
);

console.log(`Signed ${Object.keys(signatures).length} of ${CATALOG.length} listings.`);
console.log(`Unsigned on purpose: ${[...UNSIGNED_IDS].join(", ")}`);
console.log(`Signed then edited on purpose: ${TAMPERED_ID}`);
console.log(`Seller keys: ${SECRETS_PATH} (gitignored). Public wallets and signatures: ${OUT_PATH}`);
